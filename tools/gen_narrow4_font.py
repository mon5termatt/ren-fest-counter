def cols_from_rows(rows, width=4):
    out = []
    for c in range(width):
        b = 0
        for r in range(8):
            if rows[r][c] == "#":
                # LSB = bottom (row 7) per MD_MAX72XX docs
                b |= 1 << (7 - r)
        out.append(b)
    return out

first, last = 32, 122
entries = []
for code in range(first, last + 1):
    src = code - 32 if 97 <= code <= 122 else code
    if src in glyphs:
        if src == 32:
            entries.append((2, [0, 0]))
        else:
            entries.append((4, cols_from_rows(glyphs[src])))
    else:
        entries.append((0, []))

lines = [
    "// Auto-generated 4-column narrow font for MD_MAX72XX / MD_Parola",
    "// Format v1: 'F', ver, firstASCII, lastASCII, height, then per-char: width, cols...",
    "#pragma once",
    "#include <MD_MAX72xx.h>",
    "",
    "static MD_MAX72XX::fontType_t FONT_NARROW4[] PROGMEM = {",
    f"  'F', 1, {first}, {last}, 8,",
]
for code, (w, cols) in zip(range(first, last + 1), entries):
    ch = chr(code) if 32 <= code < 127 else "?"
    if w == 0:
        lines.append(f"  0,  // {code} '{ch}'")
    else:
        col_s = ", ".join(str(c) for c in cols)
        lines.append(f"  {w}, {col_s},  // {code} '{ch}'")
lines.append("};")
lines.append("")

